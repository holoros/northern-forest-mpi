def opt(c5q):
    o = dict(R.DEFAULT_OPT); o.update(NS.B1); o["view"] = "statewide"
    if c5q: o["c5_quant"] = "3q"
    return o

def extract(res, comp, row, path):
    out = []
    if not isinstance(res, dict) or "e_pt" not in res:
        return out
    for q, e in res["e_pt"].items():
        ep = float(np.asarray(e)[-1]); eb = np.asarray(res["e_bt"][q])[:, -1].astype(float)
        ok = np.isfinite(eb)
        out.append(dict(state=st, model=row, component=comp, quantity=q, ratio=np.exp(ep) if np.isfinite(ep) else np.nan,
                        lo95=np.exp(np.percentile(eb[ok], 2.5)) if ok.any() else np.nan,
                        hi95=np.exp(np.percentile(eb[ok], 97.5)) if ok.any() else np.nan,
                        n_draws_finite=int(ok.sum()), n_pairs=res.get("n"), flag=res.get("flag", ""), path=path))
    return out

def scorer_path(bb):
    rows = []
    singles = [n for n in S["singles"] if n in bb["engines"]]
    for n in singles:
        E = bb["engines"][n]
        cs_c2 = RR.comps_single(bb, n, opt(False)); cs_c5 = RR.comps_single(bb, n, opt(True))
        rows += extract(cs_c2.get("C2"), "C2_uncut", n, "scorer_draws")
        rows += extract(cs_c5.get("C5"), "C5_cut", n, "scorer_draws")
    for (name, mem, rec, how, ranked) in S["ens"]:
        mem = [x for x in mem if x in bb["engines"]]
        if rec:
            continue
        cs2, _ = RR.ensemble_comps(bb, mem, opt(False), {}, how); cs5, _ = RR.ensemble_comps(bb, mem, opt(True), {}, how)
        rows += extract(cs2.get("C2"), "C2_uncut", name, "scorer_draws")
        rows += extract(cs5.get("C5"), "C5_cut", name, "scorer_draws")
    return pd.DataFrame(rows), singles

def pairboot(bb, singles, seed=20261114, B=1000):
    rows = []
    for key, comp, cname in (("pairs", "C2", "C2_uncut"), ("treated", "C5", "C5_cut")):
        U = bb[key]; ids = pd.Index(np.asarray(U["ids"]).astype(str))
        assert ids.is_unique, f"{key} ids not unique"
        obs = pd.DataFrame({q: np.asarray(v, float) for q, v in U["obs"].items()}, index=ids)
        for n in singles:
            E = bb["engines"][n]; eng = E["engine"]; m = E.get(comp)
            if m is None or not C.eligible(eng, comp):
                continue
            if eng in C.CURVE_DRIVEN and comp == "C5":
                m = m.get(NS.B1["curve_rule"], m.get("level"))
                if m is None: continue
            if comp == "C5" and eng == "landis" and E.get("A6b_pass") is False:
                continue
            if any(C.is_xf(v) for v in m.values()): continue
            qs = C.C2_QUANT.get(eng, C.QS) if comp == "C2" else (("net_growth",) if eng == "fia_curves" else C.QS)
            mod = pd.DataFrame({q: np.asarray(m[q], float) for q in qs if q in m}, index=ids)  # model arrays are aligned to U ids by the adapter
            J = obs.add_prefix("obs_").merge(mod.add_prefix("mod_"), left_index=True, right_index=True, how="inner", validate="one_to_one")
            assert len(J) == len(ids)
            fol = bb["phi"][0] if eng in C.FOLIAGE else 1.0
            rng = np.random.default_rng(seed)
            for q in mod.columns:
                o = J[f"obs_{q}"].values; mm = J[f"mod_{q}"].values
                ok = np.isfinite(o) & np.isfinite(mm); o = o[ok]; mm = mm[ok] * fol; k = len(o)
                if k == 0: continue
                pt = mm.mean() / o.mean()
                idx = rng.integers(0, k, size=(B, k)); bt = mm[idx].mean(1) / o[idx].mean(1)
                bt = bt[np.isfinite(bt) & (bt > 0)]
                rows.append(dict(state=st, model=n, component=cname, quantity=q, ratio_pairboot=pt,
                                 lo95_pairboot=np.percentile(bt, 2.5), hi95_pairboot=np.percentile(bt, 97.5), n_pairs_pairboot=k))
    return pd.DataFrame(rows)

